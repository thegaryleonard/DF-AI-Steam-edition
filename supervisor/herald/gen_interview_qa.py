for (t, v), lst in MORE_A.items():
    QA[t]["a"][v] += lst
for (t, v), lst in MORE_H.items():
    QA[t]["h"][v] += lst

# headline templates name slots in caps for readability; the page upper-cases ALL-CAPS templates itself
UPSLOT = lambda x: re.sub(r"\{([A-Z_]+?)(?:_UP)?\}", lambda m: "{" + m.group(1).lower() + "}", x)
for d in QA.values():
    for v in d["h"]:
        d["h"][v] = [UPSLOT(x) for x in d["h"][v]]

# ---------------------------------------------------------------- write with stable ids
out = {"qa": {}, "qa_decks": {}}
for t, d in QA.items():
    o = {"q": [], "a": {}, "h": {}}
    if d["strict"] or t in ("fort", "news", "past"):
        o["strict"] = True
    for i, e in enumerate(d["q"], 1):
        o["q"].append({"id": f"qa-{t}-q{i:02d}", **e})
    for v, lst in d["a"].items():
        o["a"][v] = [{"id": f"qa-{t}-{v}-a{i:02d}", **e} for i, e in enumerate(lst, 1)]
    for v, lst in d["h"].items():
        o["h"][v] = [{"id": f"qa-{t}-{v}-h{i:02d}", "text": x} for i, x in enumerate(lst, 1)]
    out["qa"][t] = o
for k, lst in DECKS.items():
    out["qa_decks"][k] = [{"id": f"qa-deck-{k}-{i:02d}", "text": x} for i, x in enumerate(lst, 1)]
# sanity: every question 'for' names a variant that exists; every headline variant has answers
for t, o in out["qa"].items():
    for q in o["q"]:
        for v in q.get("for", []):
            assert v in o["a"], (t, q["id"], v)
        assert q["text"].endswith(("?", ".")), q["id"]
    for v in o["h"]:
        assert v in o["a"], (t, v)
json.dump(out, open(OUT, "w", encoding="utf-8", newline="\n"), indent=1, ensure_ascii=False)
