"""Write library/interview_qa.json: the Society Pages interview as topic-keyed Q&A.

Every topic has questions (q), answers per data variant (a) and headlines per variant (h). The page
(overlay.html, ==IV-BEGIN== block) works out each topic's variant from the dwarf's real data (job, skills,
squad, mood, thoughts, needs, deity, family) and the fort's live numbers, then picks a question for that
topic and an answer for that topic AND variant, so an answer always answers its own question.

Fields: q entries may carry "for": [variants] (the question presupposes that variant); a entries may carry
"tone": "up"/"down" (picked only when the dwarf's mood agrees). Slots are filled by the page (ivSlots).
Run: python herald/gen_interview_qa.py   (from supervisor/); ids are stable as long as list order is kept.
"""
import json, os, re

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "library", "interview_qa.json")

QA = {}


def topic(name, q, a, h, strict=False):
    """strict: a variant with its own questions only takes those (its answers name the subject of the question)"""
    QA[name] = {"q": q, "a": a, "h": h, "strict": strict}


def Q(*items):
    """questions: plain strings, or (text, [variants])"""
    out = []
    for x in items:
        out.append({"text": x} if isinstance(x, str) else {"text": x[0], "for": x[1]})
    return out


def A(*items):
    """answers: plain strings, or (text, tone)"""
    return [{"text": x} if isinstance(x, str) else {"text": x[0], "tone": x[1]} for x in items]


